import JSZip from 'jszip';
import type { ComponentNode } from '@/engine/types';
import { generateCss, generateHtml } from '@/engine/codegen';

export async function exportProjectZip(projectName: string, tree: ComponentNode[]): Promise<void> {
  const zip = new JSZip();
  const safeName = (projectName || 'interfacex-project').toLowerCase().replace(/[^a-z0-9_-]/g, '-');
  const css = generateCss(tree);
  const standaloneHtml = generateHtml(tree);

  // 1. package.json
  const packageJson = {
    name: safeName,
    private: true,
    version: '1.0.0',
    type: 'module',
    scripts: {
      dev: 'vite',
      build: 'vite build',
      preview: 'vite preview',
    },
    dependencies: {
      react: '^18.3.1',
      'react-dom': '^18.3.1',
    },
    devDependencies: {
      '@types/react': '^18.3.5',
      '@types/react-dom': '^18.3.0',
      '@vitejs/plugin-react': '^4.3.1',
      autoprefixer: '^10.4.18',
      postcss: '^8.4.35',
      tailwindcss: '^3.4.1',
      typescript: '^5.5.3',
      vite: '^5.4.2',
    },
  };
  zip.file('package.json', JSON.stringify(packageJson, null, 2));

  // 2. tsconfig.json
  const tsconfig = {
    compilerOptions: {
      target: 'ES2020',
      useDefineForClassFields: true,
      lib: ['ES2020', 'DOM', 'DOM.Iterable'],
      module: 'ESNext',
      skipLibCheck: true,
      moduleResolution: 'bundler',
      allowImportingTsExtensions: false,
      resolveJsonModule: true,
      isolatedModules: true,
      noEmit: true,
      jsx: 'react-jsx',
      strict: true,
      noUnusedLocals: true,
      noUnusedParameters: true,
      noFallthroughCasesInSwitch: true,
    },
    include: ['src'],
  };
  zip.file('tsconfig.json', JSON.stringify(tsconfig, null, 2));

  // 3. vite.config.ts
  const viteConfig = `import { defineConfig } from 'vite';
import react from '@vitejs/plugin-react';

export default defineConfig({
  plugins: [react()],
});
`;
  zip.file('vite.config.ts', viteConfig);

  // 4. tailwind.config.js & postcss.config.js
  zip.file(
    'tailwind.config.js',
    `/** @type {import('tailwindcss').Config} */
export default {
  content: ['./index.html', './src/**/*.{js,ts,jsx,tsx}'],
  theme: {
    extend: {},
  },
  plugins: [],
};
`
  );

  zip.file(
    'postcss.config.js',
    `export default {
  plugins: {
    tailwindcss: {},
    autoprefixer: {},
  },
};
`
  );

  // 5. index.html
  zip.file(
    'index.html',
    `<!DOCTYPE html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <title>${projectName || 'InterfaceX App'}</title>
  </head>
  <body>
    <div id="root"></div>
    <script type="module" src="/src/main.tsx"></script>
  </body>
</html>
`
  );

  // 6. src/index.css
  const indexCss = `@tailwind base;
@tailwind components;
@tailwind utilities;

${css}
`;
  zip.folder('src')?.file('index.css', indexCss);

  // 7. src/main.tsx
  const mainTsx = `import React from 'react';
import ReactDOM from 'react-dom/client';
import App from './App';
import './index.css';

ReactDOM.createRoot(document.getElementById('root')!).render(
  <React.StrictMode>
    <App />
  </React.StrictMode>
);
`;
  zip.folder('src')?.file('main.tsx', mainTsx);

  // Extract body markup from standaloneHtml
  const bodyMatch = standaloneHtml.match(/<body>([\s\S]*?)<\/body>/);
  const bodyInner = bodyMatch ? bodyMatch[1].trim() : '<div>Generated by InterfaceX</div>';

  // 8. src/App.tsx
  const appTsx = `import React from 'react';

export default function App() {
  return (
    <div className="interfacex-root" dangerouslySetInnerHTML={{ __html: ${JSON.stringify(bodyInner)} }} />
  );
}
`;
  zip.folder('src')?.file('App.tsx', appTsx);

  // 9. public/standalone.html & public/styles.css
  zip.folder('public')?.file('standalone.html', standaloneHtml);
  zip.folder('public')?.file('styles.css', css);

  // 10. README.md
  const readme = `# ${projectName || 'InterfaceX App'}

Exported from **InterfaceX** visual frontend workshop.

## Getting Started

1. **Install dependencies:**
   \`\`\`bash
   npm install
   \`\`\`

2. **Run development server:**
   \`\`\`bash
   npm run dev
   \`\`\`

3. **Build production bundle:**
   \`\`\`bash
   npm run build
   \`\`\`

---
Generated by InterfaceX on ${new Date().toLocaleString()}.
`;
  zip.file('README.md', readme);

  // Generate blob and trigger download
  const content = await zip.generateAsync({ type: 'blob' });
  const downloadUrl = URL.createObjectURL(content);
  const a = document.createElement('a');
  a.href = downloadUrl;
  a.download = `${safeName}.zip`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(downloadUrl);
}

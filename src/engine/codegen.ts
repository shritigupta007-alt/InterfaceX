import type { ComponentNode, Styles } from './types';
import { stylesToCss, TAG_NAMES, getHeadingTag } from './styles';

// Generate exported HTML and CSS that mirrors the current canvas.
// CSS targets each node by its ix-<id> class, so exported code is independent
// of runtime React keys and remains stable across renders.

function classNameFor(id: string): string {
  return `ix-${id.replace(/[^a-zA-Z0-9]/g, '')}`;
}

function esc(s: string): string {
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

function nodeHtml(node: ComponentNode, indent: number): string {
  const pad = '  '.repeat(indent);
  const tag = node.type === 'heading' ? getHeadingTag(node.props) : TAG_NAMES[node.type];
  const cls = classNameFor(node.id);

  let inner = '';
  let attrs = ` class="${cls}"`;

  switch (node.type) {
    case 'heading':
    case 'paragraph':
    case 'button':
    case 'badge':
    case 'alert':
    case 'footer':
      inner = esc(node.content);
      break;
    case 'navbar': {
      const links = (node.props.links || '').split(',').map((l) => l.trim()).filter(Boolean);
      const linksHtml = links.map((l) => `      <a href="#">${esc(l)}</a>`).join('\n');
      inner = `  <div class="${cls}-brand">${esc(node.content)}</div>\n  <div class="${cls}-links">\n${linksHtml}\n    </div>`;
      break;
    }
    case 'card':
      inner = `  <h3>${esc(node.content)}</h3>\n  <p>${esc(node.props.body || '')}</p>`;
      break;
    case 'modal':
      inner = `  <h3>${esc(node.content)}</h3>\n  <p>${esc(node.props.body || '')}</p>`;
      break;
    case 'input':
      inner = `  <label>${esc(node.props.label || 'Label')}</label>\n  <input type="${esc(node.props.inputType || 'text')}" name="${esc(node.props.name || '')}" placeholder="${esc(node.props.placeholder || '')}" />`;
      break;
    case 'form':
      inner = `  <h3>${esc(node.props.title || '')}</h3>\n  <label>Name</label>\n  <input type="text" name="name" />\n  <label>Email</label>\n  <input type="email" name="email" />\n  <button type="submit">${esc(node.props.buttonLabel || 'Submit')}</button>`;
      break;
    case 'image':
      attrs += ` src="${esc(node.content)}" alt="${esc(node.props.alt || '')}"`;
      break;
    case 'divider':
      break;
    default:
      break;
  }

  if (node.children.length > 0) {
    const childrenHtml = node.children.map((c) => nodeHtml(c, indent + 1)).join('\n');
    inner = inner ? `${inner}\n${childrenHtml}` : childrenHtml;
  }

  if (tag === 'img' || tag === 'hr') {
    return `${pad}<${tag}${attrs} />`;
  }
  if (inner) {
    return `${pad}<${tag}${attrs}>\n${inner}\n${pad}</${tag}>`;
  }
  return `${pad}<${tag}${attrs}></${tag}>`;
}

export function generateHtml(tree: ComponentNode[]): string {
  const body = tree.map((n) => nodeHtml(n, 2)).join('\n');
  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <title>Exported with InterfaceX</title>
  <link rel="stylesheet" href="styles.css" />
</head>
<body>
${body}
</body>
</html>`;
}

export function generateCss(tree: ComponentNode[]): string {
  const lines: string[] = [];
  lines.push('/* Generated by InterfaceX */');
  lines.push('* { box-sizing: border-box; }');
  lines.push('body { margin: 0; font-family: Inter, system-ui, -apple-system, sans-serif; background: #F8F9FC; color: #17182B; }');
  lines.push('');

  function walk(node: ComponentNode) {
    const cls = classNameFor(node.id);
    const css = stylesToCss(node.styles);
    const props = { ...node.styles };

    const sel = `.${cls}`;
    const decls = Object.entries(css).map(([k, v]) => `  ${k}: ${v};`).join('\n');
    if (decls) lines.push(`${sel} {\n${decls}\n}`);

    // component-specific child styles
    if (node.type === 'navbar') {
      lines.push(`${sel}-links { display: flex; gap: 24px; }`);
      lines.push(`${sel}-links a { color: inherit; text-decoration: none; font-size: 15px; }`);
    }
    if (node.type === 'input') {
      lines.push(`${sel} label { display: block; font-size: 14px; margin-bottom: 6px; font-weight: 500; color: #17182B; }`);
      lines.push(`${sel} input { width: 100%; padding: 10px 12px; border: 1px solid #D1D5E8; border-radius: 8px; font-size: 14px; }`);
    }
    if (node.type === 'form') {
      lines.push(`${sel} label { display: block; font-size: 14px; margin-bottom: 6px; font-weight: 500; }`);
      lines.push(`${sel} input { width: 100%; padding: 10px 12px; border: 1px solid #D1D5E8; border-radius: 8px; font-size: 14px; }`);
      lines.push(`${sel} h3 { margin: 0 0 8px 0; font-size: 22px; }`);
      lines.push(`${sel} button { padding: 12px 24px; border: none; border-radius: 10px; background: #7657FF; color: #fff; font-weight: 600; cursor: pointer; }`);
    }
    if (node.type === 'card' || node.type === 'modal') {
      lines.push(`${sel} h3 { margin: 0; font-size: 20px; color: #17182B; }`);
      lines.push(`${sel} p { margin: 0; font-size: 15px; color: #4A4B66; line-height: 1.5; }`);
    }
    if (node.type === 'footer') {
      lines.push(`${sel} .subtitle { font-size: 13px; opacity: 0.7; }`);
    }

    void props;
    node.children.forEach(walk);
  }

  tree.forEach(walk);
  return lines.join('\n');
}

// Self-contained HTML with inline CSS, ready to open in a browser.
export function generateStandaloneHtml(tree: ComponentNode[]): string {
  const css = generateCss(tree);
  const body = tree.map((n) => nodeHtml(n, 2)).join('\n');
  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <title>Exported with InterfaceX</title>
  <style>
${css}
  </style>
</head>
<body>
${body}
</body>
</html>`;
}

export function generatePreviewHtml(tree: ComponentNode[]): string {
  const css = generateCss(tree);
  const body = tree.map((n) => nodeHtml(n, 0)).join('\n');
  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <style>
${css}
  </style>
</head>
<body>
${body}
</body>
</html>`;
}
